#include <iostream>

using namespace std;

int main() {
	cout << endl << "64-bit";
	cout << endl << "Pointer " << sizeof(long*);
	cout << endl << "Bool " << sizeof(bool);
	cout << endl << "Char " << sizeof(char);
	cout << endl << "Short Int " << sizeof(short int);
	cout << endl << "Int " << sizeof(int);
	cout << endl << "Unsigned Int " << sizeof(unsigned int);
	cout << endl << "Long " << sizeof(long);
	cout << endl << "Long Int " << sizeof(long int);
	cout << endl << "Long Long " << sizeof(long long);
	cout << endl << "Float " << sizeof(float);
	cout << endl << "Double " << sizeof(double);
	cout << endl << "Long Double " << sizeof(long double);
	
}